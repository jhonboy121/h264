#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dequant_known_entries() {
        // Spot-check against common_tables.cpp.
        assert_eq!(G_KUI_DEQUANT_COEFF[0], [10, 13, 10, 13, 13, 16, 13, 16]);
        assert_eq!(G_KUI_DEQUANT_COEFF[6], [20, 26, 20, 26, 26, 32, 26, 32]);
        assert_eq!(G_KUI_DEQUANT_COEFF[51], [3584, 4608, 3584, 4608, 4608, 5888, 4608, 5888]);
        assert_eq!(G_KUI_DEQUANT_COEFF8X8[0][0], 320);
        assert_eq!(G_KUI_DEQUANT_COEFF8X8[0][2], 400);
        assert_eq!(G_KUI_DEQUANT_COEFF8X8[51][0], 448);
    }

    #[test]
    fn dequant_qp_periodicity() {
        // The 4x4 dequant table repeats every 6 QP steps, scaled by 1<<(qp/6).
        for (qp, row) in G_KUI_DEQUANT_COEFF.iter().enumerate() {
            let base = qp % 6;
            let shift = (qp / 6) as u32;
            let base_row = &G_KUI_DEQUANT_COEFF[base];
            for (col, (&v, &bv)) in row.iter().zip(base_row.iter()).enumerate() {
                assert_eq!(v as u32, (bv as u32) << shift, "qp={qp} col={col}");
            }
        }
    }

    #[test]
    fn dequant8x8_qp_periodicity() {
        // Unlike the 4x4 table, the 8x8 table stores only the QP%6 pattern and
        // repeats it identically every 6 QP steps; the `1 << (qp/6)` scaling is
        // applied separately in the dequant code path.
        for (qp, row) in G_KUI_DEQUANT_COEFF8X8.iter().enumerate() {
            let base = qp % 6;
            assert_eq!(*row, G_KUI_DEQUANT_COEFF8X8[base], "qp={qp}");
        }
    }

    fn is_permutation(t: &[u8], n: u8) -> bool {
        let mut seen = [false; 64];
        for &v in t {
            if v >= n || seen[v as usize] {
                return false;
            }
            seen[v as usize] = true;
        }
        t.len() == n as usize
    }

    #[test]
    fn scans_are_permutations() {
        assert!(is_permutation(&G_KUI_ZIGZAG_SCAN, 16));
        assert!(is_permutation(&G_KUI_ZIGZAG_SCAN8X8, 64));
    }

    #[test]
    fn scan_endpoints() {
        // Zig-zag always starts at DC and ends at the highest-frequency coeff.
        assert_eq!(G_KUI_ZIGZAG_SCAN[0], 0);
        assert_eq!(G_KUI_ZIGZAG_SCAN[15], 15);
        assert_eq!(G_KUI_ZIGZAG_SCAN8X8[0], 0);
        assert_eq!(G_KUI_ZIGZAG_SCAN8X8[63], 63);
        assert_eq!(G_KUI_CHROMA_DC_SCAN, [0, 16, 32, 48]);
    }
}
